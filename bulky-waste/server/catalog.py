_HEADS = sorted(((E.norm(w), c) for c, ws in _HEAD.items() for w in ws.split()), key=lambda x: -len(x[0]))
# 같은 말이 두 분류에 있으면 앞 분류가 이기도록(예: 안마의자 → 가전·전자) 우선순위 지정
_PRI = {c: i for i, c in enumerate(['유아용품', '반려동물', '운동·레저', '악기·취미', '사무·기타', '목재', '가전·전자', '가구류', '생활용품'])}


def classify(name):
    k = E.norm(name)
    raw = str(name or '').lower()
    for cat, words in _STRONG:
        if any(w in raw.replace(' ', '') for w in words):
            return cat
    best = None
    for w, c in _HEADS:
        i = k.rfind(w)
        if i < 0 or not w:
            continue
        key = (i + len(w), len(w), -_PRI[c])        # 가장 뒤에서 끝나는(머리말) → 긴 말 → 우선 분류
        if best is None or key > best[0]:
            best = (key, c)
    return best[1] if best else '기타'



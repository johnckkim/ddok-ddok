def with_expr(label, expr):
    """일반 명칭(고객 표현): 안마의자(바디프렌드), 무선 청소기(스틱형, 다이슨)"""
    expr = re.sub(r'\s+', ' ', str(expr or '')).strip()
    raw = lambda t: re.sub(r'[\s·,./\-_~:;"\'※()]', '', str(t).lower())
    if not expr or raw(expr) == raw(label) or raw(expr) in raw(label):
        return label
    m = re.match(r'^(.*)\(([^()]*)\)$', label)
    if m:
        return f'{m.group(1)}({m.group(2)}, {expr})'
    return f'{label}({expr})'


# ---------------------------------------------------------------- 규격 표기 정리
def tidy_spec(spec):
    """조례 원문 규격을 화면 표기로: '모 든 규 격'→'모든규격', '90㎝미만'→'90cm 미만', '1,000ℓ이상'→'1,000ℓ 이상'."""
    s = str(spec or '').strip()
    if not s:
        return '모든규격'
    if re.fullmatch(r'(?:\S ){2,}\S', s):          # 한 글자씩 띄운 표기
        s = s.replace(' ', '')
    s = s.replace('㎝', 'cm').replace('㎏', 'kg').replace('～', '~').replace('Kg', 'kg')
    s = re.sub(r'(?<=[^\s~])(이상|미만|이하|초과)', r' \1', s)
    s = re.sub(r'\s*~\s*', '~', s)
    s = re.sub(r'\s+', ' ', s).strip()
    if s.replace(' ', '') in ('모든규격', '모든', '규격'):
        return '모든규격'
    return s

def fallback_candidates(q, extra_hints=None):
    """쇼핑몰을 못 쓸 때 고객 표현으로 고르는 자주 쓰는 후보(id 목록)."""
    k = E.norm(q)
    out = []
    for expr, ids in (extra_hints or []):
        if expr and (expr == k or expr in k):
            out += ids
    if k in AMBIG_NOUNS:
        out += AMBIG_NOUNS[k]
    for expr, ids in HINTS:
        if expr in k:
            out += ids
    if not out:
        out = list(GENERIC)
    return list(dict.fromkeys(out))


